#' Generate checksums for REDCap-exported `.csv` and `.r` raw data files
#'
#' @param date either `"latest"` or a string of the format `YYYY-MM-DD` with the 
#' date identifying the data export to use. If there are multiple exports on a 
#' date the one with the latest time-stamp is used.
#'
#' @returns `NULL` invisibly. Saves the generated checksums as `.csv.sha256` and 
#' `.r.sha256` text files to `/03_checksums` and to 
#' `L:/AuditData/DEXA-PSYCH/15 - Databehandling/02 - REDCap raw data`
#'
#' @examples
#' 
#' ## mk_checksums()
#' 
mk_checksums <- function(date = "latest") {
  # Paths and files:
  path2checksums <- "03_checksums"
  if(!dir.exists(path2checksums)) dir.create(path2checksums)
  path2L <- "L:/AuditData/DEXA-PSYCH/15 - Databehandling/02 - REDCap raw data"
  all_fnms <- list.files(path2L)
  all_csv_fnms <- getgrep("^DEXAPSYCH-Rchrdata_DATA_.*\\.csv$", all_fnms)
  all_csv_datetimes <- gsub("^DEXAPSYCH-Rchrdata_DATA_|\\.csv$", "", all_csv_fnms)
  
  # Determine date-time to use:
  if(date == "latest") use_datetime <- max(all_csv_datetimes) else {
    if(is.Date(date)) date <- as.character(date)
    use_datetime <- getgrep(date, all_csv_datetimes)
    if(length(use_datetime) < 1) 
      stop("Cannot locate csv-file: with date '", date, "' in folder:\n", path2L)
    use_datetime <- max(use_datetime)
  }
  
  # Confirm existence of csv and r files on L:-drive:
  redcap_csv_filenm <- paste0("DEXAPSYCH-Rchrdata_DATA_", use_datetime, ".csv")
  redcap_r_filenm <- paste0("DEXAPSYCH-Rchrdata_R_", use_datetime, ".r")
  redcap_csv_path <- file.path(path2L, redcap_csv_filenm)
  redcap_r_path <- file.path(path2L, redcap_r_filenm)
  stopifnot("Cannot locate csv file: " = file.exists(redcap_csv_path),
            "Cannot locate r file: " = file.exists(redcap_r_path))
  
  # Generate and save checksums for csv and r file to (1) L-drive and 
  # (2) local git-versioned folder: '/03_checksums':
  cat("Saving SHA-256 HASH values for .csv and .r files:\n")
  for(filenm in c(redcap_csv_filenm, redcap_r_filenm)) {
    baseline_hash <- digest(file = file.path(path2L, filenm), algo = "sha256")
    hash_path_L <- paste0(path2L, "/", filenm, ".sha256")
    hash_path_local <- paste0(path2checksums, "/", filenm, ".sha256")
    cat("SHA-256 :", baseline_hash, "\n")
    writeLines(baseline_hash, hash_path_L)
    writeLines(baseline_hash, hash_path_local)
    cat("Saved to:", hash_path_L, "\n")
    cat("Saved to:", hash_path_local, "\n")
  }

  invisible(NULL)
}

#' Get date/time-stamp from saved checksums
#'
#' @returns a character vector of the form 'YYYY-MM-DD_HHMM'
#'
#' @examples
#' get_datetime_from_checksums()
get_datetime_from_checksums <- function() {
  path2checksums <- "03_checksums"
  fnms <- list.files(path2checksums)
  datetimes <- gsub("^DEXAPSYCH-Rchrdata_|DATA_|R_|\\.csv\\.sha256$|\\.r\\.sha256", "", fnms)
  if(length(unique(datetimes)) != 1) 
    stop("'csv' and 'r' checksums are invalid. Reason: multiple date-time stamps")
  
  datetimes[1L]
}


#' Test if checksums match
#' 
#' To test the integrity of the data exported from REDCap (`.csv` and `.r` files),
#' we read the expected checksums from `/03_checksums` and compare to checksums
#' freshly generated by `digest::digest` from the data files on the audited 
#' `L:`-drive.
#'
#' @param filetype the type of file to test (scalar string)
#'
#' @returns `NULL` invisibly. Errors if the expected and observed checksums do 
#' not match and messages a confirmation otherwise.
#'
#' @examples
#' 
#' test_checksums()
#' test_checksums("csv")
#' test_checksums("r")
#' 
test_checksums <- function(filetype = c("csv", "r")) {
  filetype <- match.arg(filetype)
  path2checksums <- "03_checksums"
  if(!dir.exists(path2checksums)) stop("'03_checksums' directory does not exist")
  fnms <- list.files(path2checksums)
  if(length(fnms) == 0) stop("No files found in '03_checksums' directory")
  
  # Determine .csv and .r file names:
  datetime <- get_datetime_from_checksums()
  hash_csv_filenm <- paste0("DEXAPSYCH-Rchrdata_DATA_", datetime, ".csv.sha256")
  hash_r_filenm <- paste0("DEXAPSYCH-Rchrdata_R_", datetime, ".r.sha256")
  hash_files <- c(hash_csv_filenm, hash_r_filenm)
  stopifnot(all(hash_files %in% fnms))
  
  filenm <- if(filetype == "csv") hash_csv_filenm else hash_r_filenm
  
  # Read expected checksums from /03_checksums:
  expected_hash <- trimws(readLines(file.path(path2checksums, filenm)))
  
  # Determine observed checksums from .csv and .r files:
  path2L <- "L:/AuditData/DEXA-PSYCH/15 - Databehandling/02 - REDCap raw data"
  file_path <- file.path(path2L, gsub("\\.sha256", "", filenm))
  observed_hash <- digest(file = file_path, algo = "sha256")
  
  # Message 'confirmed checksums' or stop():
  if(observed_hash == expected_hash) {
    message("Checksums confirmed for file: '", gsub("\\.sha256", "", filenm), "'")
  } else {
    stop(
      "Test of checksums FAILED for file: '", gsub("\\.sha256", "", filenm), "'\n",
      "  Expected: '", expected_hash, "'\n",
      "  Observed: '", observed_hash, "'\n")
  }
  invisible(NULL)
}


#' Read the REDCap generated file with R-code
#' 
#' First test the checksums for the file. Then read the `.r`-file by copying to
#' a local `tempfile()` to avoid delays from reading directly of the `L:`-drive.
#'
#' @returns The contents of the `.r`-file as text (character vector)
#'
#' @examples
#' 
#' rcode <- read_r_file()
#' 
read_r_file <- function() {
  # Test checksums before reading file:
  test_checksums(filetype = "r")
  
  # Determine .r file names:
  datetime <- get_datetime_from_checksums()
  path2L <- "L:/AuditData/DEXA-PSYCH/15 - Databehandling/02 - REDCap raw data"
  r_path <- file.path(path2L, paste0("DEXAPSYCH-Rchrdata_R_", datetime, ".r"))
  if(!file.exists(r_path)) stop("Cannot locate file: '", r_path, "'")
  
  # Copy-to-tempfile & read:
  TMP_FILE <- tempfile(fileext = paste0(".", tools::file_ext(r_path)))
  on.exit(unlink(TMP_FILE), add = TRUE)
  file_copy_success <- file.copy(r_path, TMP_FILE)
  rcode_file <- readLines(TMP_FILE)

  # Return R-code as text:
  rcode_file
}


#' Read the REDCap generated `.csv`-file with raw data
#' 
#' First test the checksums for the file. Then read the `.csv`-file by copying to
#' a local `tempfile()` to avoid delays from reading directly of the `L:`-drive.
#'
#' @returns The raw data as `data.table` (read using `fread`).
#'
#' @examples
#' 
#' tmp <- read_csv_file()
#' stopifnot(inherits(tmp, "data.table"))
#' 
read_csv_file <- function() {
  # Test checksums before reading file:
  test_checksums(filetype = "csv")
  
  # Determine .csv file names:
  datetime <- get_datetime_from_checksums()
  path2L <- "L:/AuditData/DEXA-PSYCH/15 - Databehandling/02 - REDCap raw data"
  csv_path <- file.path(path2L, paste0("DEXAPSYCH-Rchrdata_DATA_", datetime, ".csv"))
  if(!file.exists(csv_path)) stop("Cannot locate file: '", csv_path, "'")
  
  # Copy-to-tempfile & read:
  TMP_FILE <- tempfile(fileext = paste0(".", tools::file_ext(csv_path)))
  on.exit(unlink(TMP_FILE), add = TRUE)
  file_copy_success <- file.copy(csv_path, TMP_FILE)
  d <- fread(file=TMP_FILE, na.strings = c("", "NA", "NASK", "ASKU", "APN"))
  
  # Return data.table:
  d[]
}
